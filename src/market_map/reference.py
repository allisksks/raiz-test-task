"""Справочники: регионы РФ и каналы сбыта."""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Region:
    code: str  # ISO 3166-2:RU
    name: str
    federal_district: str
    # Варианты написания, которые встречаются в источниках (кроме полного названия)
    aliases: tuple[str, ...] = field(default=())

    @property
    def map_code(self) -> str:
        """Код региона в карте России Superset (Country Map)."""
        return SUPERSET_MAP_CODES.get(self.code, self.code)


